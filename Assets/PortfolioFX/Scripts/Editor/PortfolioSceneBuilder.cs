        [MenuItem("Portfolio FX/Build Missing Scenes")]
        public static void Build()
        {
            if (!Application.isBatchMode && !EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo()) return;
            foreach (string folder in new[] { "Scenes", "Prefabs", "Materials", "Models", "Textures", "Animations",
                "Documentation", "Shaders", "SubGraphs", "VFX", "Verification" })
                Directory.CreateDirectory(Root + "/" + folder);
            AssetDatabase.Refresh();
            PrepareResources();
            for (int i = 0; i < Names.Length; i++)
            {
                string path = Root + "/Scenes/" + Names[i] + ".unity";
                if (File.Exists(path)) { Debug.Log("PortfolioFX: preserved existing scene " + path); continue; }
                BuildScene(i);
            }
            File.WriteAllText(Root + "/Documentation/ResourceManifest.md", Manifest.ToString(), new UTF8Encoding(false));
            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();
            ValidateAndCapture();
            Debug.Log("PORTFOLIO_BUILD_SUCCESS: 12 scenes generated and validated.");
        }

