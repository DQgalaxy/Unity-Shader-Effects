        static Texture2D Capture(Camera camera,int width,int height)
        {
            var rt=RenderTexture.GetTemporary(width,height,24,RenderTextureFormat.ARGB32);
            var oldTarget=camera.targetTexture; var oldActive=RenderTexture.active;
            try
            {
                camera.targetTexture=rt; camera.Render(); RenderTexture.active=rt;
                var image=new Texture2D(width,height,TextureFormat.RGB24,false); image.ReadPixels(new Rect(0,0,width,height),0,0); image.Apply(); return image;
            }
            finally { camera.targetTexture=oldTarget; RenderTexture.active=oldActive; RenderTexture.ReleaseTemporary(rt); }
        }

        // One-time finishing pass for the newly generated scaffold, never run automatically on user work.
        public static void FinishScaffold()
        {
            GenerateTexture("SoftDisc", (u,v)=> { float a=1-SmoothThreshold(.05f,.5f,Vector2.Distance(new Vector2(u,v),Vector2.one*.5f)); return new Color(1,1,1,a*a); },false,true);
            GenerateTexture("RingMask", (u,v)=> { float d=Vector2.Distance(new Vector2(u,v),Vector2.one*.5f); float a=1-SmoothThreshold(.015f,.055f,Mathf.Abs(d-.36f)); return new Color(a,a,a,a); },true,true);
            GenerateTexture("FlameMask", (u,v)=> { float n=PeriodicNoise(u,v,6),w=(1-v)*.34f+.015f; float a=(1-SmoothThreshold(w,w+.1f,Mathf.Abs(u-.5f+(n-.5f)*.16f)))*Mathf.Sin(v*Mathf.PI); return new Color(a,a,a,a); },true,true);
            foreach(string name in new[] { "Stage", "Trim", "Metal" })
            {
                var mat=AssetDatabase.LoadAssetAtPath<Material>(Root+"/Materials/"+name+".mat");
                mat.SetFloat("_Metallic",0); mat.SetFloat("_Smoothness",.12f);
                mat.SetFloat("_SpecularHighlights",0); mat.EnableKeyword("_SPECULARHIGHLIGHTS_OFF");
                mat.SetFloat("_EnvironmentReflections",0); mat.EnableKeyword("_ENVIRONMENTREFLECTIONS_OFF");
                EditorUtility.SetDirty(mat);
            }
            foreach(string guid in AssetDatabase.FindAssets("t:Material",new[] {Root+"/Materials"}))
            {
                var mat=AssetDatabase.LoadAssetAtPath<Material>(AssetDatabase.GUIDToAssetPath(guid));
                if(!mat.name.Contains("PLACEHOLDER") || !mat.HasProperty("_Surface") || mat.GetFloat("_Surface")<.5f) continue;
                mat.shader=Shader.Find("Universal Render Pipeline/Unlit");
                mat.SetFloat("_Surface",1); mat.SetFloat("_Blend",0); mat.SetFloat("_BlendModePreserveSpecular",0);
                mat.SetFloat("_SrcBlend",(float)BlendMode.SrcAlpha); mat.SetFloat("_DstBlend",(float)BlendMode.OneMinusSrcAlpha);
                mat.SetFloat("_ZWrite",0); mat.SetFloat("_Cull",mat.name.Contains("Flame") || mat.name.Contains("GroundSlash_Energy")?0:2);
                mat.DisableKeyword("_ALPHAPREMULTIPLY_ON"); mat.EnableKeyword("_SURFACE_TYPE_TRANSPARENT");
                mat.renderQueue=3000; EditorUtility.SetDirty(mat);
            }
            for(int i=0;i<Names.Length;i++)
            {
                var scene=EditorSceneManager.OpenScene(Root+"/Scenes/"+Names[i]+".unity",OpenSceneMode.Single);
                var d=Object.FindFirstObjectByType<FXSequenceDriver>(); d.maxLightIntensity=2;
                foreach(var animator in d.GetComponentsInChildren<Animator>(true))
                {
                    if(animator.GetComponentInParent<FXCharacterMotion>()==null) DisableCharacterControls(animator.gameObject);
                }
                PortfolioFacingRepair.RepairHierarchy(d.gameObject);
                var camera=Camera.main;
                camera.transform.position=i==8?new Vector3(8,6,-10):new Vector3(5.3f,3.4f,-7.6f);
                camera.transform.LookAt(new Vector3(0,i==8?1.7f:1.1f,0));
                foreach(var light in Object.FindObjectsByType<Light>(FindObjectsSortMode.None))
                    if(light.type==LightType.Directional) light.intensity=light.name=="KeyLight"?1.15f:.35f;
                var volume=Object.FindFirstObjectByType<Volume>(); volume.priority=100;
                var profile=volume.sharedProfile;
                if(!profile.TryGet<ColorAdjustments>(out var adjust)) { adjust=profile.Add<ColorAdjustments>(); AssetDatabase.AddObjectToAsset(adjust,profile); }
                adjust.postExposure.Override(0); adjust.contrast.Override(5); adjust.saturation.Override(0); adjust.colorFilter.Override(Color.white);
                if(!profile.TryGet<Tonemapping>(out var tone)) { tone=profile.Add<Tonemapping>(); AssetDatabase.AddObjectToAsset(tone,profile); }
                tone.mode.Override(TonemappingMode.Neutral);
                EditorUtility.SetDirty(profile); EditorUtility.SetDirty(adjust); EditorUtility.SetDirty(tone);
                d.Seek(0); PrefabUtility.SaveAsPrefabAsset(d.gameObject,Root+"/Prefabs/"+Names[i]+"_FX.prefab");
                EditorSceneManager.SaveScene(scene);
            }
            AssetDatabase.SaveAssets();
            ValidateAndCapture();
        }

        public static void RebuildNewScaffold()
        {
            PrepareResources();
            for(int i=0;i<Names.Length;i++) BuildScene(i);
            File.WriteAllText(Root+"/Documentation/ResourceManifest.md",Manifest.ToString(),new UTF8Encoding(false));
            AssetDatabase.SaveAssets();
            FinishScaffold();
        }

