        static Mesh BuildBand(int segments,float start,float end,float inner,float outer)
        {
            var vertices=new Vector3[(segments+1)*2]; var uv=new Vector2[vertices.Length]; var triangles=new int[segments*6];
            for(int i=0;i<=segments;i++)
            {
                float u=i/(float)segments,a=Mathf.Lerp(start,end,u); Vector3 dir=new Vector3(Mathf.Cos(a),0,Mathf.Sin(a));
                vertices[i*2]=dir*inner; vertices[i*2+1]=dir*outer; uv[i*2]=new Vector2(u,0); uv[i*2+1]=new Vector2(u,1);
                if(i==segments) continue; int j=i*2,k=i*6; triangles[k]=j; triangles[k+1]=j+2; triangles[k+2]=j+1; triangles[k+3]=j+1; triangles[k+4]=j+2; triangles[k+5]=j+3;
            }
            var m=new Mesh { vertices=vertices,uv=uv,triangles=triangles }; m.RecalculateNormals(); m.RecalculateBounds(); return m;
        }
        static Mesh BuildGrid()
        {
            const int n=64; var vertices=new Vector3[(n+1)*(n+1)]; var uv=new Vector2[vertices.Length]; var triangles=new int[n*n*6];
            for(int z=0;z<=n;z++) for(int x=0;x<=n;x++) { int i=z*(n+1)+x; vertices[i]=new Vector3(x/(float)n*2-1,0,z/(float)n*2-1); uv[i]=new Vector2(x/(float)n,z/(float)n); }
            int k=0; for(int z=0;z<n;z++) for(int x=0;x<n;x++) { int i=z*(n+1)+x; triangles[k++]=i; triangles[k++]=i+n+1; triangles[k++]=i+1; triangles[k++]=i+1; triangles[k++]=i+n+1; triangles[k++]=i+n+2; }
            var m=new Mesh { vertices=vertices,uv=uv,triangles=triangles }; m.RecalculateNormals(); m.RecalculateBounds();
            m.bounds=new Bounds(Vector3.zero,new Vector3(2,2,2)); return m;
        }
