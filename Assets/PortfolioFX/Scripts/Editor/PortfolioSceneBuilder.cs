        static void CopyTexture(string source, string filename, bool srgb)
        {
            string target = Root + "/Textures/" + filename;
            if (!File.Exists(target) && !AssetDatabase.CopyAsset(source, target)) throw new IOException("Cannot copy " + source);
            var importer = (TextureImporter)AssetImporter.GetAtPath(target);
            importer.sRGBTexture = srgb;
            importer.wrapMode = filename.Contains("Ramp") ? TextureWrapMode.Clamp : TextureWrapMode.Repeat;
            importer.SaveAndReimport();
            Manifest.AppendLine("- `Textures/" + filename + "` <- `" + source + "` (sRGB=" + srgb + ")");
        }

        static float PeriodicNoise(float u, float v, float scale)
        {
            u = Mathf.Repeat(u,1); v = Mathf.Repeat(v,1);
            float a=Mathf.PerlinNoise(u*scale+13,v*scale+19), b=Mathf.PerlinNoise((u-1)*scale+13,v*scale+19);
            float c=Mathf.PerlinNoise(u*scale+13,(v-1)*scale+19), d=Mathf.PerlinNoise((u-1)*scale+13,(v-1)*scale+19);
            return Mathf.Lerp(Mathf.Lerp(a,b,u),Mathf.Lerp(c,d,u),v);
        }

        static float SmoothThreshold(float min, float max, float x) => Mathf.SmoothStep(0,1,Mathf.InverseLerp(min,max,x));

        static void GenerateTexture(string name, Func<float,float,Color> sample, bool linear, bool replace=false)
        {
            string path=Root+"/Textures/"+name+".png";
            if (File.Exists(path) && !replace) return;
            var tex=new Texture2D(256,256,TextureFormat.RGBA32,false,linear);
            var pixels=new Color[256*256];
            for(int y=0;y<256;y++) for(int x=0;x<256;x++) pixels[y*256+x]=sample(x/255f,y/255f);
            tex.SetPixels(pixels); tex.Apply(); File.WriteAllBytes(path,tex.EncodeToPNG()); Object.DestroyImmediate(tex);
            AssetDatabase.ImportAsset(path);
            var importer=(TextureImporter)AssetImporter.GetAtPath(path);
            importer.sRGBTexture=!linear; importer.alphaSource=TextureImporterAlphaSource.FromInput;
            importer.wrapMode=name=="NoiseRG" ? TextureWrapMode.Repeat : TextureWrapMode.Clamp;
            importer.textureCompression=TextureImporterCompression.Uncompressed; importer.SaveAndReimport();
        }

        static Material Material(string name, Color color, bool transparent, float emission, bool unlit=false)
        {
            string path=Root+"/Materials/"+name+".mat";
            var existing=AssetDatabase.LoadAssetAtPath<Material>(path);
            if(existing!=null) return existing;
            var shader=Shader.Find(unlit ? "Universal Render Pipeline/Particles/Unlit" : "Universal Render Pipeline/Lit");
            if(shader==null) throw new InvalidOperationException("URP shader unavailable");
            var m=new Material(shader) { name=name };
            m.SetColor("_BaseColor",color); m.SetFloat("_Smoothness",.55f);
            m.SetFloat("_Metallic",unlit?0:.35f); m.SetFloat("_Cull",2);
            if(emission>0 && !unlit) { m.EnableKeyword("_EMISSION"); m.SetColor("_EmissionColor",color*emission); }
            if(transparent)
            {
                m.SetFloat("_Surface",1); m.SetFloat("_Blend",0); m.SetFloat("_SrcBlend",(float)BlendMode.SrcAlpha);
                m.SetFloat("_DstBlend",(float)BlendMode.OneMinusSrcAlpha); m.SetFloat("_ZWrite",0);
                m.EnableKeyword("_SURFACE_TYPE_TRANSPARENT"); m.SetOverrideTag("RenderType","Transparent");
                m.renderQueue=(int)RenderQueue.Transparent;
            }
            AssetDatabase.CreateAsset(m,path); return m;
        }

        static void BuildScene(int index)
        {
            sceneName=Names[index]; duration=Durations[index]; accent=Colors[index];
            Bindings.Clear(); Cues.Clear(); Arcs.Clear(); TransformGroups.Clear();
            EditorSceneManager.NewScene(NewSceneSetup.EmptyScene,NewSceneMode.Single);
            RenderSettings.ambientMode=AmbientMode.Trilight;
            RenderSettings.ambientSkyColor=new Color(.45f,.48f,.5f);
            RenderSettings.ambientEquatorColor=new Color(.25f,.28f,.3f);
            RenderSettings.ambientGroundColor=new Color(.12f,.13f,.14f);
            root=new GameObject(sceneName+"_FX").transform;
            driver=root.gameObject.AddComponent<FXSequenceDriver>(); driver.duration=duration;
            clip=new AnimationClip { name=sceneName+"_Sequence", frameRate=60, legacy=true, wrapMode=WrapMode.ClampForever };
            energy=Material(sceneName+"_Energy_PLACEHOLDER",new Color(accent.r,accent.g,accent.b,.24f),true,1);
            body=Material(sceneName+"_Surface_PLACEHOLDER",accent,false,.1f);
            var center=Empty("EffectCenter",new Vector3(0,1.3f,0)); driver.center=center;
            driver.hitPoint=Empty("HitPoint",new Vector3(-.4f,1.4f,-.6f));
            Field("progress",0,0,duration*.65f,1,duration*.9f,1,duration,0);
            Field("intensity",0,0,.3f,.15f,duration*.5f,1,duration*.75f,.8f,duration*.96f,0,duration,0);
            Field("dissolve",0,0,duration,0); Field("radius",0,.1f,duration*.8f,3,duration,3);
            Field("impact",0,0,duration*.5f,1,duration*.6f,0,duration,0);
            switch(index)
            {
                case 0: BuildOverheat(); break;
                case 1: BuildCrystal(); break;
                case 2: BuildShield(); break;
                case 3: BuildFreeze(); break;
                case 4: BuildElectric(); break;
                case 5: BuildHologram(); break;
                case 6: BuildCharge(); break;
                case 7: BuildSlash(); break;
                case 8: BuildMeteor(); break;
                case 9: BuildPortal(); break;
                case 10: BuildWater(); break;
                case 11: BuildDepth(); break;
            }
            var glow=Empty("EffectLight",new Vector3(0,2,-1)).gameObject.AddComponent<Light>();
            glow.type=LightType.Point; glow.range=8; glow.color=accent; driver.effectLight=glow;
            driver.materials=Bindings.ToArray(); driver.particles=Cues.ToArray(); driver.arcs=Arcs.ToArray();
            driver.characters=root.GetComponentsInChildren<FXCharacterMotion>(true);
            string clipPath=Root+"/Animations/"+sceneName+"_Sequence.anim";
            var savedClip=AssetDatabase.LoadAssetAtPath<AnimationClip>(clipPath);
            if(savedClip!=null) { EditorUtility.CopySerialized(clip,savedClip); Object.DestroyImmediate(clip); clip=savedClip; EditorUtility.SetDirty(clip); }
            else AssetDatabase.CreateAsset(clip,clipPath);
            driver.sequence=clip;
            driver.Seek(0);
            PrefabUtility.SaveAsPrefabAsset(root.gameObject,Root+"/Prefabs/"+sceneName+"_FX.prefab");
            CreateStage(index);
            EditorSceneManager.SaveScene(EditorSceneManager.GetActiveScene(),Root+"/Scenes/"+sceneName+".unity");
            Manifest.AppendLine("- `Scenes/"+sceneName+".unity`: "+duration+"s; "+Bindings.Count+" material bindings; "+Cues.Count+" particle layers; "+Arcs.Count+" arcs.");
        }

        static Transform Empty(string name, Vector3 pos, Transform parent=null)
        {
            var t=new GameObject(name).transform; t.SetParent(parent!=null?parent:root,false); t.localPosition=pos; return t;
        }
        static GameObject Primitive(string name, PrimitiveType type, Vector3 pos, Vector3 scale, Material mat, Transform parent=null)
        {
            var go=GameObject.CreatePrimitive(type); go.name=name; go.transform.SetParent(parent!=null?parent:root,false);
            go.transform.localPosition=pos; go.transform.localScale=scale; go.GetComponent<Renderer>().sharedMaterial=mat;
            Object.DestroyImmediate(go.GetComponent<Collider>()); return go;
        }
        static GameObject MeshObject(string name, Mesh mesh, Vector3 pos, Vector3 scale, Material mat)
        {
            var t=Empty(name,pos); t.localScale=scale; t.gameObject.AddComponent<MeshFilter>().sharedMesh=mesh;
            t.gameObject.AddComponent<MeshRenderer>().sharedMaterial=mat; return t.gameObject;
        }
        static void Bind(GameObject go, FXPreviewMode mode)
        {
            foreach(var r in go.GetComponentsInChildren<Renderer>())
                if(!(r is ParticleSystemRenderer)) Bindings.Add(new FXMaterialBinding { target=r,previewMode=mode,previewColor=accent });
        }
        static GameObject Character(string name, Vector3 position, FXPreviewMode mode=FXPreviewMode.Surface)
        {
            var go=PortfolioEllenUpgrade.CreateCharacter(root,name,position,sceneName);
            foreach(var r in go.GetComponentsInChildren<SkinnedMeshRenderer>())
                Bindings.Add(new FXMaterialBinding {target=r,previewMode=mode,previewColor=accent,preserveAlbedo=true});
            return go;
        }

        static void DisableCharacterControls(GameObject go)
        {
            foreach(var behaviour in go.GetComponentsInChildren<MonoBehaviour>(true)) behaviour.enabled=false;
            foreach(var controller in go.GetComponentsInChildren<CharacterController>(true)) controller.enabled=false;
        }

        static void Curve(Transform target, string property, params float[] keys)
        {
            string path=AnimationUtility.CalculateTransformPath(target,root);
            string group=property.Substring(0,property.LastIndexOf('.'));
            // Unity packs transform curves into vectors; unkeyed components otherwise become zero.
            if(TransformGroups.Add(path+"|"+group))
            {
                Vector3 baseline=group=="m_LocalPosition"?target.localPosition:group=="m_LocalScale"?target.localScale:target.localEulerAngles;
                for(int axis=0;axis<3;axis++) clip.SetCurve(path,typeof(Transform),group+"."+"xyz"[axis],AnimationCurve.Constant(0,duration,baseline[axis]));
            }
            var curve=new AnimationCurve();
            for(int i=0;i<keys.Length;i+=2) curve.AddKey(keys[i],keys[i+1]);
            for(int i=0;i<curve.length;i++) { AnimationUtility.SetKeyLeftTangentMode(curve,i,AnimationUtility.TangentMode.Linear); AnimationUtility.SetKeyRightTangentMode(curve,i,AnimationUtility.TangentMode.Linear); }
            clip.SetCurve(path,typeof(Transform),property,curve);
        }
        static void Field(string name, params float[] keys)
        {
            var curve=new AnimationCurve();
            for(int i=0;i<keys.Length;i+=2) curve.AddKey(keys[i],keys[i+1]);
            for(int i=0;i<curve.length;i++) { AnimationUtility.SetKeyLeftTangentMode(curve,i,AnimationUtility.TangentMode.Linear); AnimationUtility.SetKeyRightTangentMode(curve,i,AnimationUtility.TangentMode.Linear); }
            clip.SetCurve("",typeof(FXSequenceDriver),name,curve);
        }
        static void Scale(Transform t, params float[] keys)
        { Curve(t,"m_LocalScale.x",keys); Curve(t,"m_LocalScale.y",keys); Curve(t,"m_LocalScale.z",keys); }
        static void Ring(string name, Vector3 position, float start, float end, float maxRadius, bool vertical=false)
        {
            var go=MeshObject(name,ring,position,Vector3.one,energy); if(vertical) go.transform.localEulerAngles=new Vector3(90,0,0);
            Bind(go,FXPreviewMode.Energy);
            Scale(go.transform,0,.001f,start,.001f,start+.08f,.15f,end,maxRadius,end+.08f,.001f,duration,.001f);
        }
        static ParticleSystem Particles(string name, Vector3 position, Color color, float start, float stop, float rate, float speed, float size, float lifetime, SkinnedMeshRenderer skin=null)
        {
            var t=Empty(name,position); var ps=t.gameObject.AddComponent<ParticleSystem>(); ps.Stop(true,ParticleSystemStopBehavior.StopEmittingAndClear);
            var main=ps.main; main.playOnAwake=false; main.loop=true; main.duration=duration; main.startLifetime=lifetime;
            main.startSpeed=new ParticleSystem.MinMaxCurve(speed*.5f,speed); main.startSize=new ParticleSystem.MinMaxCurve(size*.5f,size);
            main.startColor=color; main.maxParticles=400; main.simulationSpace=ParticleSystemSimulationSpace.World;
            ps.useAutoRandomSeed=false; ps.randomSeed=(uint)(Cues.Count+111);
            var emission=ps.emission; emission.rateOverTime=rate;
            var shape=ps.shape; shape.shapeType=ParticleSystemShapeType.Sphere; shape.radius=.18f;
            if(skin!=null) { shape.shapeType=ParticleSystemShapeType.SkinnedMeshRenderer; shape.skinnedMeshRenderer=skin; }
            var vel=ps.velocityOverLifetime; vel.enabled=true; vel.space=ParticleSystemSimulationSpace.World; vel.y=.35f;
            var col=ps.colorOverLifetime; col.enabled=true; var gradient=new Gradient();
            gradient.SetKeys(new[] { new GradientColorKey(color,0),new GradientColorKey(color*.5f,1) },new[] { new GradientAlphaKey(0,0),new GradientAlphaKey(1,.12f),new GradientAlphaKey(0,1) }); col.color=gradient;
            var sz=ps.sizeOverLifetime; sz.enabled=true; sz.size=new ParticleSystem.MinMaxCurve(1,AnimationCurve.EaseInOut(0,1,1,0));
            ps.GetComponent<ParticleSystemRenderer>().sharedMaterial=particle;
            Cues.Add(new FXParticleCue { system=ps,start=start,stop=stop }); return ps;
        }
        static void Arc(string name, Transform a, Transform b, float start, float end, int seed)
        {
            var go=Empty(name,Vector3.zero).gameObject; var line=go.AddComponent<LineRenderer>(); line.useWorldSpace=true;
